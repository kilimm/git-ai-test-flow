// 本文件所有改动要求遵循 agent-rules 规范
import Database from 'better-sqlite3';

export interface PostgresExportOptions {
  sourcePath: string;
  includeData?: boolean;
  schema?: string;
}

interface SqliteObject {
  type: 'table' | 'index' | 'view';
  name: string;
  sql: string;
}

const SKIPPED_TABLES = new Set(['__drizzle_migrations']);

function isFtsObject(name: string): boolean {
  return name.endsWith('_fts') || name.includes('_fts_');
}

function quoteIdentifier(value: string): string {
  return `"${value.replaceAll('"', '""')}"`;
}

function literal(value: unknown): string {
  if (value === null || value === undefined) {
    return 'NULL';
  }

  if (Buffer.isBuffer(value)) {
    return `decode('${value.toString('hex')}', 'hex')`;
  }

  if (typeof value === 'number') {
    return Number.isFinite(value) ? String(value) : 'NULL';
  }

  if (typeof value === 'bigint') {
    return value.toString();
  }

  return `'${String(value).replaceAll("'", "''")}'`;
}

function convertTableSql(sql: string): string {
  return (
    sql
      .replaceAll('`', '"')
      .replace(/\binteger\b/gi, 'bigint')
      .replace(/\bblob\b/gi, 'bytea')
      .replace(/\bTEXT\b/g, 'text')
      .replace(/\bBLOB\b/g, 'bytea')
      // SQLite 布尔以整数存储；保留整数语义，避免 PostgreSQL bigint 接受 boolean 默认值。
      .replace(/\bDEFAULT true\b/gi, 'DEFAULT 1')
      .replace(/\bDEFAULT false\b/gi, 'DEFAULT 0')
  );
}

/** 拓扑排序保证带外键的数据按被引用表优先写入。 */
function orderTables(database: Database.Database, tables: readonly SqliteObject[]): SqliteObject[] {
  const byName = new Map(tables.map((table) => [table.name, table]));
  const visited = new Set<string>();
  const result: SqliteObject[] = [];

  const visit = (table: SqliteObject): void => {
    if (visited.has(table.name)) {
      return;
    }

    visited.add(table.name);
    const foreignKeys = database
      .prepare(`PRAGMA foreign_key_list(${quoteIdentifier(table.name)})`)
      .all() as Array<{ table: string }>;

    for (const foreignKey of foreignKeys) {
      const parent = byName.get(foreignKey.table);

      if (parent !== undefined && parent.name !== table.name) {
        visit(parent);
      }
    }

    result.push(table);
  };

  for (const table of tables) {
    visit(table);
  }

  return result;
}

/**
 * SQLite → PostgreSQL 迁移导出：
 * - 转换反引号、integer→bigint、blob→bytea，保留主键/唯一索引/外键；
 * - 跳过 SQLite FTS5 虚拟表，需在 PostgreSQL 另行建立全文索引；
 * - includeData 在事务中按外键拓扑顺序写入；
 * - 平台运行时的元数据库仍是 SQLite，本工具用于迁移评估和分析库。
 */
export function exportPostgresSql(options: PostgresExportOptions): string {
  const database = new Database(options.sourcePath, { readonly: true, fileMustExist: true });
  const schema = options.schema ?? 'public';
  const lines: string[] = [
    '-- Generated by git-ai-test-flow SQLite → PostgreSQL exporter',
    '-- FTS5 is SQLite-specific and must be rebuilt with PostgreSQL full-text indexes.',
    `CREATE SCHEMA IF NOT EXISTS ${quoteIdentifier(schema)};`,
    `SET search_path TO ${quoteIdentifier(schema)};`,
    '',
  ];

  try {
    const objects = database
      .prepare(
        "SELECT type, name, sql FROM sqlite_master WHERE type IN ('table','index') AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name",
      )
      .all() as SqliteObject[];
    const tables = objects.filter(
      (object) =>
        object.type === 'table' && !SKIPPED_TABLES.has(object.name) && !isFtsObject(object.name),
    );
    const ordered = orderTables(database, tables);

    for (const table of ordered) {
      lines.push(`-- table ${table.name}`, `${convertTableSql(table.sql)};`, '');
    }

    for (const index of objects.filter(
      (object) => object.type === 'index' && !isFtsObject(object.name),
    )) {
      lines.push(`${convertTableSql(index.sql)};`, '');
    }

    if (options.includeData === true) {
      lines.push('BEGIN;', '');

      for (const table of ordered) {
        const columns = database
          .prepare(`PRAGMA table_info(${quoteIdentifier(table.name)})`)
          .all() as Array<{ name: string }>;
        const rows = database
          .prepare(`SELECT * FROM ${quoteIdentifier(table.name)}`)
          .all() as Array<Record<string, unknown>>;
        const names = columns.map((column) => quoteIdentifier(column.name)).join(', ');

        for (const row of rows) {
          const values = columns.map((column) => literal(row[column.name])).join(', ');

          lines.push(
            `INSERT INTO ${quoteIdentifier(table.name)} (${names}) VALUES (${values}) ON CONFLICT DO NOTHING;`,
          );
        }
      }

      lines.push('', 'COMMIT;', '');
    }

    return lines.join('\n');
  } finally {
    database.close();
  }
}
